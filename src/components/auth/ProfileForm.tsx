import { useLingui } from "@lingui/react";
import {
	Avatar,
	Badge,
	Button,
	Card,
	Group,
	PasswordInput,
	Radio,
	SimpleGrid,
	Stack,
	Text,
	TextInput,
} from "@mantine/core";
import { schemaResolver, useForm } from "@mantine/form";
import {
	useQuery,
	useQueryClient,
	useSuspenseQuery,
} from "@tanstack/react-query";
import { useRouter } from "@tanstack/react-router";
import { LocalDate } from "#/components/ui/LocalDate";
import { SectionCard } from "#/components/ui/SectionCard";
import { avatarPresets } from "#/config/avatars.ts";
import { roles } from "#/config/permissions.ts";
import { updateProfileFn } from "#/features/auth/auth.functions.ts";
import { userQueryOptions } from "#/features/auth/auth.query.ts";
import type { UpdateProfileInput } from "#/features/auth/schema.ts";
import { UpdateProfileSchema } from "#/features/auth/schema.ts";
import { twoFactorStatusQueryOptions } from "#/features/auth/security.query.ts";
import { teamDisplayName } from "#/features/teams/labels.ts";
import { teamContextQueryOptions } from "#/features/teams/teams.query.ts";
import { LocalizedLink } from "#/libs/i18n.ts";
import { useAppMutation } from "../ui/useAppMutation";

/**
 * Profile settings for the signed-in user: a summary card, then name and
 * email, avatar and password sections, saved together. Every save requires the current password; the server re-checks
 * it. Reads the user from the query primed by the root route. The avatar
 * picker offers initials or avatars generated by Nitrobase itself
 * (`#/config/avatars.ts`); a custom https URL set earlier stays selectable.
 */
export const ProfileForm: React.FC = () => {
	const { i18n } = useLingui();
	const { data: user } = useSuspenseQuery(userQueryOptions);
	const { data: teamContext } = useQuery(teamContextQueryOptions);
	const { data: twoFactor } = useQuery(twoFactorStatusQueryOptions);
	const router = useRouter();
	const queryClient = useQueryClient();
	const presets = avatarPresets().map((preset) => preset.url);
	const current = user?.avatarUrl ?? "";
	// Initials ("") first, then generated presets, then a custom URL if any.
	const avatarOptions = [
		"",
		...presets,
		...(current && !presets.includes(current) ? [current] : []),
	];
	const name = `${user?.firstName ?? ""} ${user?.lastName ?? ""}`.trim();

	// Controlled: the avatar highlight and the Save button follow every edit.
	const form = useForm<UpdateProfileInput>({
		mode: "controlled",
		initialValues: {
			firstName: user?.firstName ?? "",
			lastName: user?.lastName ?? "",
			email: user?.email ?? "",
			currentPassword: "",
			newPassword: "",
			avatarUrl: current,
		},
		validate: schemaResolver(UpdateProfileSchema(i18n), { sync: true }),
	});

	const save = useAppMutation({
		mutationFn: (values: UpdateProfileInput) =>
			updateProfileFn({ data: values }),
		form,
		success: i18n._("Profile updated."),
		onSuccess: async () => {
			// Never keep passwords in the form after a successful save, and make
			// the saved values the new "clean" baseline.
			form.setFieldValue("currentPassword", "");
			form.setFieldValue("newPassword", "");
			form.resetDirty();

			// Refresh both the query cache and route loaders/context (the user is
			// also exposed through router context, e.g. in the header).
			await queryClient.invalidateQueries(userQueryOptions);
			await router.invalidate();
		},
	});

	const team = teamContext?.team;
	const dirty = form.isDirty();

	return (
		<form onSubmit={form.onSubmit((values) => save.mutate(values))}>
			<Stack gap="lg">
				<Card p="lg">
					<Group gap="lg" wrap="nowrap" align="center">
						<Avatar
							src={form.values.avatarUrl || undefined}
							name={name}
							color="initials"
							size={72}
							radius="xl"
							alt=""
						/>
						<Stack gap={4} style={{ minWidth: 0 }}>
							<Text fz="lg" fw={600} truncate>
								{name}
							</Text>
							<Text size="sm" c="dimmed" truncate>
								{user?.email}
							</Text>
							<Group gap="xs" mt={4}>
								{team && (
									<Badge variant="light" color="gray">
										{i18n._(roles[team.role].label)} ·{" "}
										{teamDisplayName(i18n, team.name)}
									</Badge>
								)}
								{twoFactor && (
									<Badge
										component={LocalizedLink}
										to="/settings/security"
										variant="light"
										color={twoFactor.enabled ? "green" : "yellow"}
										style={{ cursor: "pointer" }}
									>
										{twoFactor.enabled ? i18n._("2FA on") : i18n._("2FA off")}
									</Badge>
								)}
								{user?.createdAt && (
									<Text size="xs" c="dimmed">
										{i18n._("Member since")}{" "}
										<LocalDate value={user.createdAt} />
									</Text>
								)}
							</Group>
						</Stack>
					</Group>
				</Card>

				<SectionCard
					title={i18n._("Personal information")}
					description={i18n._("Your name and sign-in email.")}
				>
					<Stack gap="md">
						<SimpleGrid cols={{ base: 1, sm: 2 }} spacing="md">
							<TextInput
								label={i18n._("First name")}
								autoComplete="given-name"
								{...form.getInputProps("firstName")}
							/>
							<TextInput
								label={i18n._("Last name")}
								autoComplete="family-name"
								{...form.getInputProps("lastName")}
							/>
						</SimpleGrid>
						<TextInput
							label={i18n._("Email address")}
							type="email"
							autoComplete="email"
							{...form.getInputProps("email")}
						/>
					</Stack>
				</SectionCard>

				<SectionCard
					title={i18n._("Avatar")}
					description={i18n._(
						"Your initials or a generated avatar. Nothing is loaded from other sites.",
					)}
				>
					{/* Radio group: Tab reaches it, arrow keys move the choice. */}
					<Radio.Group
						aria-label={i18n._("Avatar")}
						value={form.values.avatarUrl ?? ""}
						onChange={(value) => form.setFieldValue("avatarUrl", value)}
						error={form.errors.avatarUrl}
					>
						<Group gap="sm">
							{avatarOptions.map((url, index) => (
								<Radio.Card
									key={url || "initials"}
									value={url}
									w="auto"
									p={4}
									radius="xl"
									aria-label={
										url
											? i18n._("Avatar {number}", { number: index })
											: i18n._("Initials")
									}
								>
									<Avatar
										src={url || undefined}
										name={name}
										color="initials"
										size="lg"
										radius="xl"
										alt=""
									/>
								</Radio.Card>
							))}
						</Group>
					</Radio.Group>
				</SectionCard>

				<SectionCard
					title={i18n._("Password")}
					description={i18n._("Leave empty to keep current password")}
				>
					<PasswordInput
						label={i18n._("New password")}
						placeholder={i18n._("New password")}
						autoComplete="new-password"
						maw={420}
						{...form.getInputProps("newPassword")}
					/>
				</SectionCard>

				<SectionCard
					title={i18n._("Save changes")}
					description={i18n._(
						"Enter your current password to confirm any change.",
					)}
				>
					<Group align="flex-end" gap="sm" wrap="wrap">
						<PasswordInput
							label={i18n._("Current password")}
							placeholder={i18n._("Your current password")}
							autoComplete="current-password"
							style={{ flex: "1 1 260px" }}
							maw={420}
							{...form.getInputProps("currentPassword")}
						/>
						<Group gap="xs" ml="auto">
							{dirty && (
								<Button
									variant="default"
									onClick={() => form.reset()}
									disabled={save.isPending}
								>
									{i18n._("Discard")}
								</Button>
							)}
							<Button type="submit" loading={save.isPending} disabled={!dirty}>
								{i18n._("Save changes")}
							</Button>
						</Group>
					</Group>
				</SectionCard>
			</Stack>
		</form>
	);
};
